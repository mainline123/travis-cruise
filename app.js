    function getStatusBadge(status) {
        const stat =
            (status || '')
                .toLowerCase()
                .trim();

        if (stat === 'in port') {
            return (
                `<span class="status-badge badge-in-port">` +
                `IN PORT</span>`
            );
        }

        if (stat === 'expected') {
            return (
                `<span class="status-badge badge-expected">` +
                `EXPECTED</span>`
            );
        }

        if (stat === 'scheduled') {
            return (
                `<span class="status-badge badge-scheduled">` +
                `SCHEDULED</span>`
            );
        }

        if (stat === 'departed') {
            return (
                `<span class="status-badge badge-departed">` +
                `DEPARTED</span>`
            );
        }

        if (stat === 'cancelled') {
            return (
                `<span class="status-badge badge-cancelled">` +
                `CANCELLED</span>`
            );
        }

        return (
            `<span class="status-badge">` +
            `${(status || '').toUpperCase()}` +
            `</span>`
        );
    }

