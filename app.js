    function getPortClass(port) {
        const name =
            (port || '')
                .toLowerCase();

        if (name.includes('montego')) {
            return 'port-montego';
        }

        if (name.includes('falmouth')) {
            return 'port-falmouth';
        }

        if (name.includes('ocho')) {
            return 'port-ocho';
        }

        if (name.includes('kingston')) {
            return 'port-kingston';
        }

        return '';
    }

    function cleanPortName(port) {
        const name =
            (port || '')
                .toLowerCase()
                .trim();

        if (name.includes('montego')) {
            return 'Montego Bay';
        }

        if (name.includes('falmouth')) {
            return 'Falmouth';
        }

        if (name.includes('ocho')) {
            return 'Ocho Rios';
        }

        if (name.includes('kingston')) {
            return 'Kingston';
        }

        return port;
    }

