    function getTargetDate() {
        const urlParams =
            new URLSearchParams(window.location.search);

        const dateParam =
            urlParams.get('date');

        if (
            dateParam &&
            /^\d{4}-\d{2}-\d{2}$/.test(dateParam)
        ) {
            return dateParam;
        }

        const now = new Date();

        const jamaicaTime =
            new Date(now.getTime() - (5 * 60 * 60 * 1000));

        const year =
            jamaicaTime.getUTCFullYear();

        const month =
            String(jamaicaTime.getUTCMonth() + 1)
                .padStart(2, '0');

        const day =
            String(jamaicaTime.getUTCDate())
                .padStart(2, '0');

        return `${year}-${month}-${day}`;
    }

    function formatTime12Hour(timeStr) {
        if (!timeStr || timeStr === '--:--') {
            return '--:--';
        }

        const parts =
            timeStr.split(':');

        if (parts.length < 2) {
            return timeStr;
        }

        let hours =
            parseInt(parts[0], 10);

        const minutes =
            parts[1];

        const ampm =
            hours >= 12 ? 'PM' : 'AM';

        hours =
            hours % 12;

        if (hours === 0) {
            hours = 12;
        }

        return (
            `${String(hours).padStart(2, '0')}:` +
            `${minutes} ${ampm}`
        );
    }

    function formatDateDisplay(dateStr) {
        if (!dateStr) {
            return '---';
        }

        const parts =
            dateStr.split('-');

        if (parts.length < 3) {
            return dateStr;
        }

        const months = [
            'Jan',
            'Feb',
            'Mar',
            'Apr',
            'May',
            'Jun',
            'Jul',
            'Aug',
            'Sep',
            'Oct',
            'Nov',
            'Dec'
        ];

        const monthIdx =
            parseInt(parts[1], 10) - 1;

        const day =
            parseInt(parts[2], 10);

        return `${months[monthIdx]} ${day}`;
    }

    function timeToMinutes(timeStr) {
        if (!timeStr || timeStr === '--:--') {
            return 9999;
        }

        const match12 =
            timeStr.match(
                /(\d+):(\d+)\s*(AM|PM)/i
            );

        if (match12) {
            let hours =
                parseInt(match12[1], 10);

            const minutes =
                parseInt(match12[2], 10);

            const ampm =
                match12[3].toUpperCase();

            if (
                ampm === 'PM' &&
                hours < 12
            ) {
                hours += 12;
            }

            if (
                ampm === 'AM' &&
                hours === 12
            ) {
                hours = 0;
            }

            return (
                hours * 60 +
                minutes
            );
        }

        const parts =
            timeStr.split(':');

        if (parts.length >= 2) {
            return (
                parseInt(parts[0], 10) * 60 +
                parseInt(parts[1], 10)
            );
        }

        return 9999;
    }

    // ============================================================
    // SHIP STATUS
    // ============================================================

    function calculateStatus(
        arriveTimeStr,
        departTimeStr,
        shipDateStr,
        todayDateStr
    ) {

        if (shipDateStr > todayDateStr) {
            return 'Scheduled';
        }

        if (shipDateStr < todayDateStr) {
            return 'Departed';
        }

        const now =
            new Date();

        const jamaicaTime =
            new Date(
                now.getTime() -
                (5 * 60 * 60 * 1000)
            );

        const currentMinutes =
            jamaicaTime.getUTCHours() * 60 +
            jamaicaTime.getUTCMinutes();

        const arrMin =
            timeToMinutes(arriveTimeStr);

        const depMin =
            timeToMinutes(departTimeStr);

        if (
            arrMin === 9999 &&
            depMin === 9999
        ) {
            return 'Scheduled';
        }

        if (
            arrMin !== 9999 &&
            depMin !== 9999
        ) {

            if (currentMinutes < arrMin) {
                return 'Expected';
            }

            if (
                currentMinutes >= arrMin &&
                currentMinutes <= depMin
            ) {
                return 'In Port';
            }

            return 'Departed';
        }

        if (arrMin !== 9999) {
            return (
                currentMinutes < arrMin
                    ? 'Expected'
                    : 'In Port'
            );
        }

        if (depMin !== 9999) {
            return (
                currentMinutes <= depMin
                    ? 'In Port'
                    : 'Departed'
            );
        }

        return 'Scheduled';
    }

    // ============================================================
    // PORT FUNCTIONS
